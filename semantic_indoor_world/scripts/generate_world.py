#!/usr/bin/env python3
"""Generate worlds/my_map.world and config/semantic_map.yaml from world_layout.py.

    python3 scripts/generate_world.py
    python3 scripts/generate_world.py --rubi-world ../rubi_gazebo_sim/worlds/my_map.world \
        --rubi-template ../rubi_gazebo_sim/worlds/rubi_controller.world

--rubi-world also writes a variant with the RUBI robot. Its <include> block for
model://RUBI (with the controller plugin) and the start support box are copied
from the template world, so the robot setup stays exactly as in that world.
"""

import argparse
from pathlib import Path
import re
import sys

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import world_layout as L  # noqa: E402

PACKAGE = HERE.parent
HEADER = ('<!-- GENERATED by scripts/generate_world.py from scripts/world_layout.py.\n'
          '     Do not edit by hand: change world_layout.py and regenerate. -->\n')


def _f(value):
    text = f'{value:.4f}'.rstrip('0').rstrip('.')
    return '0' if text in ('-0', '') else text


def _pose(x, y, z, yaw):
    return f'{_f(x)} {_f(y)} {_f(z)} 0 0 {_f(yaw)}'


def _color(rgba):
    return ' '.join(_f(c) for c in rgba)


def box_sdf(box, indent):
    sx, sy, sz = box.size
    size = f'{_f(sx)} {_f(sy)} {_f(sz)}'
    pad = ' ' * indent
    transparency = 1.0 - box.color[3]
    lines = [f'{pad}<collision name="{box.name}_collision">',
             f'{pad}  <pose>{_pose(*box.pose)}</pose>',
             f'{pad}  <geometry><box><size>{size}</size></box></geometry>',
             f'{pad}</collision>'] if box.collide else []
    lines += [f'{pad}<visual name="{box.name}_visual">',
              f'{pad}  <pose>{_pose(*box.pose)}</pose>',
              f'{pad}  <geometry><box><size>{size}</size></box></geometry>',
              f'{pad}  <material>',
              f'{pad}    <ambient>{_color(box.color)}</ambient>',
              f'{pad}    <diffuse>{_color(box.color)}</diffuse>',
              f'{pad}    <specular>0.1 0.1 0.1 1</specular>',
              f'{pad}  </material>']
    if transparency > 0:
        lines.append(f'{pad}  <transparency>{_f(transparency)}</transparency>')
    lines.append(f'{pad}</visual>')
    return lines


def model_sdf(model):
    lines = [f'    <model name="{model.name}">',
             '      <static>true</static>',
             f'      <pose>{_pose(*model.pose)}</pose>',
             '      <link name="link">']
    for box in model.boxes:
        lines += box_sdf(box, 8)
    lines += ['      </link>', '    </model>']
    return '\n'.join(lines)


GROUND = '''    <model name="ground_plane">
      <static>true</static>
      <link name="link">
        <collision name="collision">
          <geometry><plane><normal>0 0 1</normal><size>40 40</size></plane></geometry>
          <surface><friction><ode><mu>100</mu><mu2>50</mu2></ode></friction></surface>
        </collision>
        <visual name="visual">
          <cast_shadows>false</cast_shadows>
          <geometry><plane><normal>0 0 1</normal><size>40 40</size></plane></geometry>
          <material><ambient>0.6 0.6 0.6 1</ambient><diffuse>0.7 0.7 0.7 1</diffuse></material>
        </visual>
      </link>
    </model>'''

LIGHT = '''    <light name="sun" type="directional">
      <cast_shadows>true</cast_shadows>
      <pose>0 0 10 0 0 0</pose>
      <diffuse>0.85 0.85 0.85 1</diffuse>
      <specular>0.2 0.2 0.2 1</specular>
      <direction>-0.4 0.2 -0.9</direction>
    </light>'''

# max_step_size 0.002 matches the RUBI controller plugin's requirement, so the
# same environment can host RUBI without changing physics.
PHYSICS = '''    <physics name="default_physics" default="1" type="ode">
      <max_step_size>0.002</max_step_size>
      <real_time_factor>1</real_time_factor>
      <real_time_update_rate>500</real_time_update_rate>
      <ode>
        <solver>
          <type>quick</type>
          <iters>100</iters>
          <sor>1.0</sor>
          <use_dynamic_moi_rescaling>false</use_dynamic_moi_rescaling>
        </solver>
      </ode>
    </physics>'''

GUI = '''    <gui fullscreen="0">
      <camera name="user_camera">
        <pose>0 -17 19 0 0.85 1.5708</pose>
        <view_controller>orbit</view_controller>
      </camera>
    </gui>'''


def world_sdf(extra=''):
    models = '\n\n'.join(model_sdf(m) for m in L.all_models())
    return (f'<?xml version="1.0" ?>\n{HEADER}<sdf version="1.6">\n'
            '  <world name="semantic_indoor_world">\n'
            f'{PHYSICS}\n{GUI}\n'
            '    <scene><ambient>0.5 0.5 0.5 1</ambient><shadows>true</shadows></scene>\n'
            f'{LIGHT}\n{GROUND}\n\n{models}\n{extra}'
            '  </world>\n</sdf>\n')


def _rubi_extra(template_path, model='RUBI'):
    """RUBI include + start support box from the template, moved to ROBOT_SPAWN.

    `model` swaps the included robot (e.g. RUBI_mid360_imu for LiDAR + IMU) while
    keeping the template's controller plugin block unchanged.
    """
    text = Path(template_path).read_text(encoding='utf-8')
    include = re.search(r'\s*<include>\s*<uri>model://RUBI</uri>.*?</include>', text, re.S)
    support = re.search(r'\s*<model name="box">.*?</model>', text, re.S)
    if not include:
        raise SystemExit(f'{template_path}: no <include> with model://RUBI found')
    block = include.group(0).replace('<uri>model://RUBI</uri>', f'<uri>model://{model}</uri>')
    sx, sy, syaw = L.ROBOT_SPAWN

    def shift(block):
        def move(match):
            x, y, z, r, p, yaw = (float(v) for v in match.group(1).split())
            return f'<pose>{_f(x + sx)} {_f(y + sy)} {_f(z)} {_f(r)} {_f(p)} {_f(yaw + syaw)}</pose>'
        return re.sub(r'<pose>([^<]+)</pose>', move, block, count=1)

    parts = [f'\n    <!-- {model} with the controller from ' + Path(template_path).name
             + f', spawned at ({_f(sx)}, {_f(sy)}) -->']
    if support:
        parts.append(shift(support.group(0)).replace('name="box"', 'name="rubi_start_support"'))
    parts.append(shift(block))
    return '\n'.join(p.rstrip() for p in parts) + '\n'


def _num(v):
    return round(float(v), 4) + 0.0


def semantic_yaml():
    rooms, objects = L.semantic_targets()
    lines = ['# GENERATED by scripts/generate_world.py from scripts/world_layout.py.',
             '# object_pose: Gazebo world pose of the object / reference point of the space.',
             '# navigation_goal: reachable Nav2 goal (x, y, yaw) in the same frame.',
             '# Coordinates are Gazebo world ground truth; see README about aligning with',
             '# a SLAM-built map frame.',
             'map:',
             '  name: semantic_indoor_world',
             '  frame_id: map',
             '  world_file: my_map.world',
             f'  width: {_num(L.BUILDING_X)}',
             f'  height: {_num(L.BUILDING_Y)}',
             '  origin: building_center',
             '  bounds:',
             f'    x_min: {_num(L.X_MIN)}',
             f'    x_max: {_num(L.X_MAX)}',
             f'    y_min: {_num(L.Y_MIN)}',
             f'    y_max: {_num(L.Y_MAX)}',
             '',
             'navigation_config:',
             f'  robot_radius: {_num(L.ROBOT_RADIUS)}',
             f'  min_goal_clearance: {_num(L.MIN_GOAL_CLEARANCE)}',
             '  # goals keep at least robot_radius + min_goal_clearance from collision surfaces',
             f'  required_obstacle_distance: {_num(L.REQUIRED_CLEARANCE)}',
             f'  obstacle_max_height: {_num(L.OBSTACLE_MAX_HEIGHT)}',
             f'  grid_resolution: {_num(L.GRID_RESOLUTION)}',
             '']

    def pose_lines(key, pose, with_z=True):
        out = [f'    {key}:', f'      x: {_num(pose[0])}', f'      y: {_num(pose[1])}']
        if with_z:
            out.append(f'      z: {_num(pose[2])}')
        out.append(f'      yaw: {_num(pose[-1])}')
        return out

    def entry(target_id, data):
        out = [f'  {target_id}:', f'    name: "{data["name"]}"']
        if 'room' in data:
            out.append(f'    room: {data["room"]}')
        out.append('    aliases:')
        out += [f'      - "{a}"' for a in data['aliases']]
        out += pose_lines('object_pose', data['object_pose'])
        out += pose_lines('navigation_goal', data['navigation_goal'], with_z=False)
        if 'region' in data:
            out.append('    region:  # floor polygon [x, y], counter-clockwise')
            out += [f'      - [{_num(x)}, {_num(y)}]' for x, y in data['region']]
        return out + ['']

    lines.append('rooms:')
    for target_id, data in rooms.items():
        lines += entry(target_id, data)
    lines.append('objects:')
    for target_id, data in objects.items():
        lines += entry(target_id, data)
    lines.append('doors:')
    for door_id, d in L.doors().items():
        lines += [f'  {door_id}:', f'    rooms: [{", ".join(d["rooms"])}]',
                  f'    width: {_num(d["width"])}',
                  f'    center: [{_num(d["center"][0])}, {_num(d["center"][1])}]',
                  f'    span: {{axis: {d["span"]["axis"]}, min: {_num(d["span"]["min"])}, '
                  f'max: {_num(d["span"]["max"])}}}']
    lines += ['', 'robot_spawn:', f'  x: {_num(L.ROBOT_SPAWN[0])}',
              f'  y: {_num(L.ROBOT_SPAWN[1])}', f'  yaw: {_num(L.ROBOT_SPAWN[2])}']
    return '\n'.join(lines) + '\n'


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--world', default=str(PACKAGE / 'worlds' / 'my_map.world'))
    parser.add_argument('--yaml', default=str(PACKAGE / 'config' / 'semantic_map.yaml'))
    parser.add_argument('--rubi-world', default='', help='also write a variant with RUBI here')
    parser.add_argument('--rubi-template', default='',
                        help='world to copy the RUBI include block from')
    parser.add_argument('--rubi-model', default='RUBI',
                        help='robot model to include, e.g. RUBI_mid360_imu (LiDAR + IMU)')
    args = parser.parse_args(argv)

    Path(args.world).write_text(world_sdf(), encoding='utf-8')
    Path(args.yaml).write_text(semantic_yaml(), encoding='utf-8')
    print(f'wrote {args.world}\nwrote {args.yaml}')
    if args.rubi_world:
        if not args.rubi_template:
            parser.error('--rubi-world needs --rubi-template')
        Path(args.rubi_world).write_text(world_sdf(_rubi_extra(args.rubi_template,
                                                               args.rubi_model)),
                                         encoding='utf-8')
        print(f'wrote {args.rubi_world}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
